def detect_ai_patterns(paragraphs: list[Paragraph]) -> list[dict[str, object]]:
    rows: list[dict[str, object]] = []
    for unit in style_prose_units():
        for severity, category, assessment, pattern, recommendation in PATTERNS:
            text = str(unit["text"])
            for match in pattern.finditer(text):
                left, right = max(0, match.start() - 90), min(len(text), match.end() + 140)
                rows.append(
                    {
                        "paragraph_id": unit["paragraph_id"],
                        "chapter": unit["chapter"],
                        "path": unit["path"],
                        "line_start": unit["line_start"],
                        "line_end": unit["line_end"],
                        "severity": severity,
                        "category": category,
                        "trigger": match.group(0),
                        "assessment": assessment,
                        "excerpt": text[left:right],
                        "recommendation": recommendation,
                    }
                )
    # The user's approved writing contract intentionally asks for 3--5 sentence
    # paragraphs.  Report rhythm uniformity but identify it as a specification
    # trade-off, not evidence of authorship.
    for chapter in sorted({item.chapter for item in paragraphs}):
        chapter_items = [item for item in paragraphs if item.chapter == chapter]
        in_band = sum(3 <= item.sentences <= 5 for item in chapter_items)
        if chapter_items and in_band / len(chapter_items) >= 0.65:
            rows.append(
                {
                    "paragraph_id": "",
                    "chapter": chapter,
                    "path": "(chapter aggregate)",
                    "line_start": "",
                    "line_end": "",
                    "severity": "P2",
                    "category": "uniform_paragraph_rhythm",
                    "trigger": f"{in_band}/{len(chapter_items)} paragraphs contain 3--5 sentences",
                    "assessment": "judgment call: this follows the author's explicit 3--5 sentence contract",
                    "excerpt": "",
                    "recommendation": "Vary sentence length inside the required paragraph envelope; do not violate the approved contract mechanically.",
                }
            )
    write_csv(
        artifact("ai-writing-flags.csv"),
        rows,
        [
            "paragraph_id", "chapter", "path", "line_start", "line_end",
            "severity", "category", "trigger", "assessment", "excerpt", "recommendation",
        ],
    )
    return rows


