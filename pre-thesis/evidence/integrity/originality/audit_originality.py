"""Reproducible Stage 2.5 originality and AI-writing audit.

The selected document is scoped to the active input graph rooted at either
``pre-thesis/main.tex`` or ``pre-thesis/monograph/main.tex``.  It resolves
literal ``\\iffalse``/``\\iftrue``
branches and entry-point ``\\ifdefined`` switches, excludes
non-prose display environments, inventories prose paragraphs, selects a
deterministic stratified sample, detects style patterns, and compares the
active prose with the author's local draft corpora.

It does not decide whether text was generated by AI and it is not a substitute
for Turnitin or iThenticate.  Outputs are heuristic audit evidence only.
"""

