def logical_corpus_path(source: Path, corpus: str) -> str:
    """Keep frozen audit locators stable after the physical work/ relocation."""

    relative = source.relative_to(ROOT).as_posix()
    if corpus == "work" and relative.startswith("material/compendios/"):
        return "work/" + relative.removeprefix("material/compendios/")
    return relative


def split_plain_blocks(text: str, source: Path, corpus: str) -> Iterator[tuple[str, str, int, str]]:
    for index, block in enumerate(re.split(r"\n\s*\n", text), 1):
        plain = latex_to_text(block) if source.suffix.lower() == ".tex" else re.sub(r"\s+", " ", block).strip()
        words = normalized_words(plain)
        if len(words) >= 20:
            yield corpus, logical_corpus_path(source, corpus), index, plain


def corpus_documents() -> list[tuple[str, str, int, str]]:
    documents: list[tuple[str, str, int, str]] = []
    for corpus, bases in CORPUS_BASES.items():
        for base in bases:
            if not base.exists():
                continue
            for path in sorted(base.rglob("*")):
                if not path.is_file():
                    continue
                suffix = path.suffix.lower()
                if suffix in {".tex", ".md", ".txt"}:
                    text = path.read_text(encoding="utf-8", errors="replace")
                    if suffix == ".tex":
                        try:
                            text = blank_display_environments(active_literal_branches(text))
                        except ValueError:
                            text = strip_comments_preserve_lines(text)
                    documents.extend(split_plain_blocks(text, path, corpus))
                elif suffix == ".pdf":
                    process = subprocess.run(
                        ["pdftotext", "-enc", "UTF-8", str(path), "-"],
                        stdout=subprocess.PIPE,
                        stderr=subprocess.DEVNULL,
                        check=False,
                    )
                    text = process.stdout.decode("utf-8", errors="replace")
                    documents.extend(split_plain_blocks(text, path, corpus))
    # Identical generated/exported blocks need not be compared repeatedly.
    unique: dict[tuple[str, str], tuple[str, str, int, str]] = {}
    for document in documents:
        corpus, _, _, text = document
        digest = hashlib.sha256(" ".join(normalized_words(text)).encode()).hexdigest()
        unique.setdefault((corpus, digest), document)
    return list(unique.values())


def write_corpus_inventory() -> list[dict[str, object]]:
    """Hash every textual source considered by the local-overlap audit."""

    provisional: list[dict[str, object]] = []
    for corpus, bases in CORPUS_BASES.items():
        for base in bases:
            if not base.exists():
                continue
            for path in sorted(base.rglob("*")):
                if not path.is_file() or path.suffix.lower() not in CORPUS_TEXT_SUFFIXES:
                    continue
                digest = hashlib.sha256(path.read_bytes()).hexdigest()
                provisional.append(
                    {
                        "corpus": corpus,
                        "path": logical_corpus_path(path, corpus),
                        "suffix": path.suffix.lower(),
                        "bytes": path.stat().st_size,
                        "sha256": digest,
                    }
                )
    groups = Counter((str(row["corpus"]), str(row["sha256"])) for row in provisional)
    canonical = {
        key: min(str(row["path"]) for row in provisional if (str(row["corpus"]), str(row["sha256"])) == key)
        for key in groups
    }
    rows = [
        {
            **row,
            "duplicate_group_size": groups[(str(row["corpus"]), str(row["sha256"]))],
            "canonical_duplicate_path": canonical[(str(row["corpus"]), str(row["sha256"]))],
            "comparison_status": "INCLUDED_TEXT_EXTRACTION",
        }
        for row in provisional
    ]
    write_csv(
        artifact("corpus-inventory.csv"),
        rows,
        [
            "corpus", "path", "suffix", "bytes", "sha256", "duplicate_group_size",
            "canonical_duplicate_path", "comparison_status",
        ],
    )
    return rows


def current_corpus_hashes() -> dict[tuple[str, str], str]:
    """Return the exact current corpus membership and hashes."""

    rows: dict[tuple[str, str], str] = {}
    for corpus, bases in CORPUS_BASES.items():
        for base in bases:
            if not base.exists():
                continue
            for path in sorted(base.rglob("*")):
                if path.is_file() and path.suffix.lower() in CORPUS_TEXT_SUFFIXES:
                    rel = logical_corpus_path(path, corpus)
                    rows[(corpus, rel)] = hashlib.sha256(path.read_bytes()).hexdigest()
    return rows


def shingles(text: str, width: int = 5) -> set[tuple[str, ...]]:
    words = normalized_words(text)
    return {tuple(words[index : index + width]) for index in range(max(0, len(words) - width + 1))}


def overlap_audit(
    paragraphs: list[Paragraph],
    documents: list[tuple[str, str, int, str]] | None = None,
) -> list[dict[str, object]]:
    if documents is None:
        documents = corpus_documents()
    doc_shingles = [shingles(text) for _, _, _, text in documents]
    index: dict[tuple[str, ...], set[int]] = defaultdict(set)
    for doc_index, values in enumerate(doc_shingles):
        for value in values:
            index[value].add(doc_index)
    rows: list[dict[str, object]] = []
    for paragraph in paragraphs:
        own = shingles(paragraph.text)
        candidates: Counter[int] = Counter()
        for value in own:
            candidates.update(index.get(value, ()))
        best: dict[str, tuple[float, float, int, int]] = {}
        for candidate, common in candidates.items():
            corpus, _, _, _ = documents[candidate]
            other = doc_shingles[candidate]
            containment = common / max(1, len(own))
            jaccard = common / max(1, len(own | other))
            score = (containment, jaccard, common, candidate)
            if corpus not in best or score > best[corpus]:
                best[corpus] = score
        for corpus in ("snapshot", "legacy_snapshot", "thesis", "paper", "work"):
            if corpus == "snapshot" and paragraph.path.startswith(
                "pre-thesis/sections/source-snapshot/"
            ):
                rows.append(
                    {
                        "paragraph_id": paragraph.paragraph_id,
                        "chapter": paragraph.chapter,
                        "current_path": paragraph.path,
                        "current_line": paragraph.line_start,
                        "corpus": corpus,
                        "source_path": paragraph.path,
                        "source_block": paragraph.line_start,
                        "common_5grams": len(own),
                        "containment_current": 1.0,
                        "jaccard": 1.0,
                        "match_type": "EXACT_OR_CONTAINED",
                        "determination": "LEGITIMATE_CANONICAL_SOURCE_COPY; provenance must remain declared",
                        "current_excerpt": paragraph.text[:240],
                        "source_excerpt": paragraph.text[:240],
                    }
                )
                continue
            if corpus not in best:
                continue
            containment, jaccard, common, candidate = best[corpus]
            if containment < 0.20 and common < 3:
                continue
            _, source_path, source_block, source_text = documents[candidate]
            if containment >= 0.98:
                match_type = "EXACT_OR_CONTAINED"
            elif containment >= 0.80:
                match_type = "HIGH_OVERLAP"
            elif containment >= 0.50:
                match_type = "MODERATE_OVERLAP"
            else:
                match_type = "LOW_OVERLAP"
            if corpus == "snapshot":
                determination = "LEGITIMATE_CANONICAL_SOURCE_COPY; provenance must remain declared"
            elif corpus == "legacy_snapshot":
                determination = "LEGITIMATE_AUTHOR_PROJECT_SNAPSHOT; historical reuse, not independent evidence"
            elif corpus == "thesis":
                determination = "LEGITIMATE_UNPUBLISHED_REVISION; not a separate publication"
            elif corpus == "work":
                determination = "LEGITIMATE_AUTHOR_DRAFT_REUSE; retain provenance, re-synthesize if copied wholesale"
            else:
                determination = "AUTHOR_STATUS_CONFIRMATION_REQUIRED; cite/rephrase if paper was submitted or published"
            rows.append(
                {
                    "paragraph_id": paragraph.paragraph_id,
                    "chapter": paragraph.chapter,
                    "current_path": paragraph.path,
                    "current_line": paragraph.line_start,
                    "corpus": corpus,
                    "source_path": source_path,
                    "source_block": source_block,
                    "common_5grams": common,
                    "containment_current": round(containment, 6),
                    "jaccard": round(jaccard, 6),
                    "match_type": match_type,
                    "determination": determination,
                    "current_excerpt": paragraph.text[:240],
                    "source_excerpt": source_text[:240],
                }
            )
    write_csv(
        artifact("self-overlap.csv"),
        rows,
        [
            "paragraph_id", "chapter", "current_path", "current_line", "corpus",
            "source_path", "source_block", "common_5grams", "containment_current",
            "jaccard", "match_type", "determination", "current_excerpt", "source_excerpt",
        ],
    )
    return rows


def rolling_word_windows(text: str, *, width: int = 180, stride: int = 90) -> list[str]:
    words = WORD_RE.findall(text)
    if not words:
        return []
    if len(words) <= width:
        return [" ".join(words)]
    windows = [" ".join(words[start : start + width]) for start in range(0, len(words) - width + 1, stride)]
    if len(words) - width not in range(0, len(words) - width + 1, stride):
        windows.append(" ".join(words[-width:]))
    return windows


def fetch_author_work(work: dict[str, object]) -> tuple[list[tuple[str, str]], str]:
    request = urllib.request.Request(
        str(work["comparison_url"]),
        headers={"User-Agent": "VIU-MROB-TFM-originality-audit/1.0"},
    )
    with urllib.request.urlopen(request, timeout=60) as response:
        payload = response.read(50_000_000)
    if work["comparison_mode"] == "full_text_pdf":
        reader = PdfReader(io.BytesIO(payload))
        blocks: list[tuple[str, str]] = []
        for page_number, page in enumerate(reader.pages, 1):
            page_text = page.extract_text() or ""
            for window_number, window in enumerate(rolling_word_windows(page_text), 1):
                blocks.append((f"page-{page_number}-window-{window_number}", window))
        return blocks, f"FULL_TEXT_PDF:{len(reader.pages)} pages"
    record = json.loads(payload.decode("utf-8", errors="replace"))
    message = record.get("message", {}) if isinstance(record, dict) else {}
    title = " ".join(str(value) for value in message.get("title", []) if value)
    abstract = html.unescape(re.sub(r"<[^>]+>", " ", str(message.get("abstract") or "")))
    text = re.sub(r"\s+", " ", f"{title}. {abstract}").strip()
    status = "METADATA_PLUS_ABSTRACT" if abstract else "METADATA_TITLE_ONLY"
    return [("crossref-record", text)], status


def audit_prior_publications(paragraphs: list[Paragraph]) -> list[dict[str, object]]:
    rows: list[dict[str, object]] = []
    works_rows: list[dict[str, object]] = []
    for work in AUTHOR_WORKS:
        try:
            blocks, source_status = fetch_author_work(work)
            error = ""
        except Exception as exc:  # Network evidence must fail visibly, not abort local artifacts.
            blocks, source_status, error = [], "FETCH_FAILED", str(exc)
        works_rows.append(
            {
                **work,
                "checked_at_utc": dt.datetime.now(dt.timezone.utc).replace(microsecond=0).isoformat(),
                "source_status": source_status,
                "comparison_blocks": len(blocks),
                "error": error,
            }
        )
        if not blocks:
            continue
        block_shingles = [shingles(text) for _, text in blocks]
        index: dict[tuple[str, ...], set[int]] = defaultdict(set)
        for block_index, values in enumerate(block_shingles):
            for value in values:
                index[value].add(block_index)
        for paragraph in paragraphs:
            own = shingles(paragraph.text)
            candidates: Counter[int] = Counter()
            for value in own:
                candidates.update(index.get(value, ()))
            if not candidates:
                continue
            candidate, common = candidates.most_common(1)[0]
            other = block_shingles[candidate]
            containment = common / max(1, len(own))
            jaccard = common / max(1, len(own | other))
            if common < 3 and containment < 0.10:
                continue
            if containment >= 0.98:
                match_type = "VERBATIM_OR_CONTAINED"
                verdict = "FAIL_REVIEW_REQUIRED"
            elif containment >= 0.80:
                match_type = "HIGH_OVERLAP"
                verdict = "FAIL_REVIEW_REQUIRED"
            elif containment >= 0.50:
                match_type = "MODERATE_OVERLAP"
                verdict = "FAIL_REVIEW_REQUIRED"
            else:
                match_type = "LOW_OVERLAP"
                verdict = "PASS_NO_CLOSE_MATCH"
            block_id, source_text = blocks[candidate]
            rows.append(
                {
                    "work_id": work["work_id"],
                    "work_title": work["title"],
                    "work_year": work["year"],
                    "source_status": source_status,
                    "paragraph_id": paragraph.paragraph_id,
                    "chapter": paragraph.chapter,
                    "current_path": paragraph.path,
                    "current_line": paragraph.line_start,
                    "source_block": block_id,
                    "common_5grams": common,
                    "containment_current": round(containment, 6),
                    "jaccard": round(jaccard, 6),
                    "match_type": match_type,
                    "verdict": verdict,
                    "current_excerpt": paragraph.text[:240],
                    "source_excerpt": source_text[:240],
                }
            )
    write_csv(
        artifact("author-prior-works.csv"),
        works_rows,
        [
            "work_id", "title", "year", "type", "metadata_url", "comparison_url",
            "comparison_mode", "checked_at_utc", "source_status", "comparison_blocks", "error",
        ],
    )
    write_csv(
        artifact("author-prior-work-overlap.csv"),
        rows,
        [
            "work_id", "work_title", "work_year", "source_status", "paragraph_id", "chapter",
            "current_path", "current_line", "source_block", "common_5grams", "containment_current",
            "jaccard", "match_type", "verdict", "current_excerpt", "source_excerpt",
        ],
    )
    return rows


def repository_metadata() -> dict[str, object]:
    def git(*args: str) -> str:
        process = subprocess.run(
            ["git", *args], cwd=ROOT, text=True, encoding="utf-8", errors="replace",
            stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, check=False,
        )
        return process.stdout.strip()

    return {
        "checked_at_utc": dt.datetime.now(dt.timezone.utc).replace(microsecond=0).isoformat(),
        "git_commit": git("rev-parse", "HEAD"),
        "git_branch": git("branch", "--show-current"),
        "worktree_dirty": bool(git("status", "--porcelain", "--untracked-files=no")),
        "audit_script_sha256": hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
        "python": sys.version.split()[0],
        "commands": [
            f"python pre-thesis/evidence/integrity/originality/audit_originality.py --document {DOCUMENT_SCOPE} --all",
            f"python pre-thesis/evidence/integrity/originality/audit_originality.py --document {DOCUMENT_SCOPE} --author-works",
            f"python pre-thesis/evidence/integrity/originality/audit_originality.py --document {DOCUMENT_SCOPE} --sync-external",
            f"python pre-thesis/evidence/integrity/originality/audit_originality.py --document {DOCUMENT_SCOPE} --check",
        ],
    }


def write_machine_summary(
    paragraphs: list[Paragraph],
    flags: list[dict[str, object]],
    overlaps: list[dict[str, object]],
    corpus_files: list[dict[str, object]],
) -> None:
    by_severity = Counter(str(row["severity"]) for row in flags)
    by_category = Counter(str(row["category"]) for row in flags)
    overlap_summary: dict[str, dict[str, int]] = {}
    for corpus in ("snapshot", "legacy_snapshot", "thesis", "paper", "work"):
        corpus_rows = [row for row in overlaps if row["corpus"] == corpus]
        overlap_summary[corpus] = {
            "rows": len(corpus_rows),
            "exact_or_contained": sum(row["match_type"] == "EXACT_OR_CONTAINED" for row in corpus_rows),
            "high_overlap": sum(row["match_type"] == "HIGH_OVERLAP" for row in corpus_rows),
            "moderate_overlap": sum(row["match_type"] == "MODERATE_OVERLAP" for row in corpus_rows),
        }
    prose_units = style_prose_units()
    summary = {
        "schema_version": 1,
        "document": DOCUMENT_SCOPE,
        **repository_metadata(),
        "entrypoint": ENTRYPOINT.relative_to(ROOT).as_posix(),
        "document_pdf": document_pdf_metadata(),
        "paragraphs_total": len(paragraphs),
        "paragraphs_sampled": sum(item.sampled for item in paragraphs),
        "sampling_rate": round(sum(item.sampled for item in paragraphs) / max(1, len(paragraphs)), 6),
        "active_prose_units_style_scanned": len(prose_units),
        "active_prose_words_style_scanned": sum(
            len(normalized_words(str(unit["text"]))) for unit in prose_units
        ),
        "ai_flags_by_severity": {
            severity: by_severity.get(severity, 0) for severity in ("P0", "P1", "P2")
        },
        "ai_flags_by_category": dict(sorted(by_category.items())),
        "self_overlap": overlap_summary,
        "corpus_files": dict(sorted(Counter(str(row["corpus"]) for row in corpus_files).items())),
        "external_web_review": f"see {artifact('external-search-audit.csv').name}",
        "disclaimer": "Heuristic screening; not a professional plagiarism or AI-authorship determination.",
    }
    artifact("machine-summary.json").write_text(
        json.dumps(summary, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )


def check_outputs() -> int:
    required = [
        artifact("paragraph-inventory.csv"),
        artifact("originality-sample.csv"),
        artifact("inventory-summary.json"),
        artifact("ai-writing-flags.csv"),
        artifact("ai-writing-checklist.csv"),
        artifact("self-overlap.csv"),
        artifact("corpus-inventory.csv"),
        artifact("machine-summary.json"),
        artifact("external-search-audit.csv"),
        artifact("author-prior-works.csv"),
        artifact("author-prior-work-overlap.csv"),
    ]
    missing = [path.name for path in required if not path.is_file()]
    if missing:
        print(json.dumps({"verdict": "FAIL", "missing": missing}, indent=2))
        return 2
    summary = json.loads(artifact("inventory-summary.json").read_text(encoding="utf-8"))
    chapters = summary["by_chapter"]
    uncovered = [chapter for chapter, counts in chapters.items() if counts["sampled"] < 1]
    current_hashes = {
        path.relative_to(ROOT).as_posix(): hashlib.sha256(path.read_bytes()).hexdigest()
        for path in active_graph()
    }
    stored_hashes = summary.get("active_file_sha256", {})
    with artifact("external-search-audit.csv").open(encoding="utf-8", newline="") as handle:
        external_rows = list(csv.DictReader(handle))
    external_ids = {row.get("paragraph_id", "") for row in external_rows}
    with artifact("originality-sample.csv").open(encoding="utf-8", newline="") as handle:
        sample_rows = list(csv.DictReader(handle))
    sample_ids = {row.get("paragraph_id", "") for row in sample_rows}
    external_by_id = {row.get("paragraph_id", ""): row for row in external_rows}
    external_sample_alignment = (
        len(external_rows) == len(sample_rows)
        and len(external_by_id) == len(external_rows)
        and external_ids == sample_ids
        and all(
            external_by_id[row.get("paragraph_id", "")].get("exact_query")
            == row.get("exact_query")
            and external_by_id[row.get("paragraph_id", "")].get("unquoted_query")
            == row.get("unquoted_query")
            for row in sample_rows
        )
    )
    sample_status_alignment = external_sample_alignment and all(
        row.get("search_status")
        == external_by_id[row.get("paragraph_id", "")].get("verdict")
        for row in sample_rows
    )
    fragment_lengths_valid = all(
        8 <= len(WORD_RE.findall(row.get("query_fragment", ""))) <= 12
        for row in sample_rows
    )
    external_rules_pass = all(
        row.get("verdict") == "ORIGINAL"
        and row.get("exact_exact_in_snippet", "").casefold() == "false"
        and int(row.get("longest_consecutive_query_words", "0") or 0) < 5
        for row in external_rows
    )
    with artifact("author-prior-works.csv").open(encoding="utf-8", newline="") as handle:
        author_works = list(csv.DictReader(handle))
    with artifact("author-prior-work-overlap.csv").open(encoding="utf-8", newline="") as handle:
        author_overlap = list(csv.DictReader(handle))
    with artifact("corpus-inventory.csv").open(encoding="utf-8", newline="") as handle:
        corpus_inventory = list(csv.DictReader(handle))
    stored_corpus_hashes = {
        (row.get("corpus", ""), row.get("path", "")): row.get("sha256", "")
        for row in corpus_inventory
    }
    corpus_hashes_current = bool(stored_corpus_hashes) and stored_corpus_hashes == current_corpus_hashes()
    author_sources_ready = bool(author_works) and all(
        row.get("source_status") not in {"", "FETCH_FAILED"} for row in author_works
    )
    author_close_matches = [row for row in author_overlap if row.get("verdict") != "PASS_NO_CLOSE_MATCH"]
    current_pdf = document_pdf_metadata()
    stored_pdf = summary.get("document_pdf", {})
    pdf_hash_current = bool(current_pdf.get("exists")) and current_pdf == stored_pdf
    verdict = (
        summary["sample_rate"] >= 0.30
        and not uncovered
        and summary.get("document") == DOCUMENT_SCOPE
        and summary.get("entrypoint") == ENTRYPOINT.relative_to(ROOT).as_posix()
        and summary["active_file_sha256"].get(ENTRYPOINT.relative_to(ROOT).as_posix())
        and current_hashes == stored_hashes
        and external_sample_alignment
        and sample_status_alignment
        and fragment_lengths_valid
        and external_rules_pass
        and corpus_hashes_current
        and author_sources_ready
        and not author_close_matches
        and pdf_hash_current
    )
    print(
        json.dumps(
            {
                "verdict": "PASS" if verdict else "FAIL",
                "paragraphs": summary["total_paragraphs"],
                "sampled": summary["sampled_paragraphs"],
                "rate": summary["sample_rate"],
                "uncovered_chapters": uncovered,
                "external_rows": len(external_rows),
                "external_sample_alignment": external_sample_alignment,
                "sample_status_alignment": sample_status_alignment,
                "fragment_lengths_valid": fragment_lengths_valid,
                "external_rules_pass": external_rules_pass,
                "corpus_hashes_current": corpus_hashes_current,
                "active_graph_hashes_current": current_hashes == stored_hashes,
                "pdf_hash_current": pdf_hash_current,
                "pdf_sha256": current_pdf.get("sha256", ""),
                "author_sources_ready": author_sources_ready,
                "author_close_matches": len(author_close_matches),
            },
            indent=2,
            ensure_ascii=False,
        )
    )
    return 0 if verdict else 2


def sync_external_status() -> int:
    """Copy reviewed web verdicts into the deterministic sample ledger."""

    sample_path = artifact("originality-sample.csv")
    external_path = artifact("external-search-audit.csv")
    if not sample_path.is_file() or not external_path.is_file():
        print(json.dumps({"verdict": "FAIL", "reason": "missing sample or external ledger"}))
        return 2
    with sample_path.open(encoding="utf-8", newline="") as handle:
        reader = csv.DictReader(handle)
        fields = list(reader.fieldnames or [])
        sample_rows = list(reader)
    with external_path.open(encoding="utf-8", newline="") as handle:
        external_rows = list(csv.DictReader(handle))
    by_key = {
        (
            row.get("paragraph_id", ""),
            row.get("exact_query", ""),
            row.get("unquoted_query", ""),
        ): row.get("verdict", "")
        for row in external_rows
    }
    missing: list[str] = []
    for row in sample_rows:
        key = (
            row.get("paragraph_id", ""),
            row.get("exact_query", ""),
            row.get("unquoted_query", ""),
        )
        if key not in by_key:
            missing.append(row.get("paragraph_id", ""))
        else:
            row["search_status"] = by_key[key]
    if missing:
        print(json.dumps({"verdict": "FAIL", "missing_external_rows": missing}, indent=2))
        return 2
    write_csv(sample_path, sample_rows, fields)
    print(json.dumps({"verdict": "PASS", "synced_rows": len(sample_rows)}, indent=2))
    return 0


def merge_external_ledgers() -> int:
    """Align reviewed query results with both frozen deterministic samples."""

    result_fields = [
        "exact_query", "exact_result_count", "exact_exact_in_snippet",
        "exact_top_url", "exact_top_title", "exact_urls_first_five",
        "unquoted_query", "unquoted_result_count",
        "longest_consecutive_query_words", "unquoted_top_url",
        "unquoted_top_title", "unquoted_urls_first_five", "verdict",
        "rationale", "checked_at_utc",
    ]
    source_paths = [
        OUTPUT / "external-search-audit.csv",
        *sorted(OUTPUT.glob("external-new-part-*.csv")),
    ]
    results: dict[tuple[str, str], dict[str, str]] = {}
    for path in source_paths:
        if not path.is_file():
            print(json.dumps({"verdict": "FAIL", "missing": path.name}, indent=2))
            return 2
        with path.open(encoding="utf-8-sig", newline="") as handle:
            for row in csv.DictReader(handle):
                key = (row.get("exact_query", ""), row.get("unquoted_query", ""))
                if key in results and any(
                    results[key].get(field, "") != row.get(field, "")
                    for field in result_fields
                    if field not in {"rationale", "checked_at_utc"}
                ):
                    raise ValueError(f"Conflicting external results for query: {key[0]}")
                results[key] = {field: row.get(field, "") for field in result_fields}

    counts: dict[str, int] = {}
    for document in ("thesis", "monograph"):
        configure_document(document)
        sample_path = artifact("originality-sample.csv")
        with sample_path.open(encoding="utf-8", newline="") as handle:
            sample_rows = list(csv.DictReader(handle))
        aligned: list[dict[str, object]] = []
        missing: list[str] = []
        for index, sample in enumerate(sample_rows, 1):
            key = (sample.get("exact_query", ""), sample.get("unquoted_query", ""))
            if key not in results:
                missing.append(sample.get("paragraph_id", ""))
                continue
            aligned.append(
                {
                    "index": index,
                    "paragraph_id": sample.get("paragraph_id", ""),
                    "chapter": sample.get("chapter", ""),
                    **results[key],
                }
            )
        if missing:
            print(json.dumps({"verdict": "FAIL", "document": document, "missing": missing}, indent=2))
            return 2
        write_csv(
            artifact("external-search-audit.csv"),
            aligned,
            ["index", "paragraph_id", "chapter", *result_fields],
        )
        counts[document] = len(aligned)
    print(json.dumps({"verdict": "PASS", "aligned_rows": counts}, indent=2))
    return 0


def generate_all_evidence(
    document: str,
    documents: list[tuple[str, str, int, str]] | None = None,
) -> tuple[list[tuple[str, str, int, str]], dict[str, object]]:
    """Generate one document's local evidence, optionally reusing extraction."""

    configure_document(document)
    OUTPUT.mkdir(parents=True, exist_ok=True)
    paragraphs = inventory()
    if not paragraphs:
        raise RuntimeError(f"No active prose paragraphs were extracted for {document}")
    write_inventory(paragraphs)
    flags = detect_ai_patterns(paragraphs)
    write_ai_checklist(paragraphs, flags)
    corpus_files = write_corpus_inventory()
    if documents is None:
        documents = corpus_documents()
    overlaps = overlap_audit(paragraphs, documents)
    write_machine_summary(paragraphs, flags, overlaps, corpus_files)
    return documents, {
        "document": document,
        "paragraphs": len(paragraphs),
        "sampled": sum(item.sampled for item in paragraphs),
        "sample_rate": round(sum(item.sampled for item in paragraphs) / len(paragraphs), 6),
        "ai_flags": len(flags),
        "overlap_rows": len(overlaps),
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--document", choices=("thesis", "monograph", "both"), default="thesis", help="Select the frozen active document graph")
    parser.add_argument("--all", action="store_true", help="Regenerate inventory, flags, and overlap audit")
    parser.add_argument("--author-works", action="store_true", help="Fetch and compare identified prior author works")
    parser.add_argument("--sync-external", action="store_true", help="Sync reviewed web verdicts into the sample ledger")
    parser.add_argument("--merge-external", action="store_true", help="Merge reviewed query partitions into both final ledgers")
    parser.add_argument("--check", action="store_true", help="Validate generated audit artifacts")
    args = parser.parse_args(argv)
    if args.merge_external:
        return merge_external_ledgers()
    if args.document == "both":
        if not args.all:
            parser.error("--document both is supported only with --all")
        # Extract the static comparison corpora once.  Monograph is selected
        # during extraction so its explicitly enabled proof branches are not
        # lost; the same superset is then used for both current-document scans.
        configure_document("monograph")
        shared_documents = corpus_documents()
        summaries: list[dict[str, object]] = []
        for document in ("thesis", "monograph"):
            shared_documents, summary = generate_all_evidence(document, shared_documents)
            summaries.append(summary)
        print(json.dumps(summaries, indent=2, ensure_ascii=False))
        return 0
    configure_document(args.document)
    if args.check:
        return check_outputs()
    if args.author_works:
        OUTPUT.mkdir(parents=True, exist_ok=True)
        paragraphs = inventory()
        rows = audit_prior_publications(paragraphs)
        print(json.dumps({"prior_work_overlap_rows": len(rows)}, indent=2))
        return 0
    if args.sync_external:
        return sync_external_status()
    if not args.all:
        parser.error("choose --all, --author-works, --sync-external, or --check")
    _, summary = generate_all_evidence(args.document)
    print(json.dumps(summary, indent=2, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
